"""Generate the Blowfish initial P-array and S-boxes (fractional hex digits of pi).

Writes src/xi/blowfish_table.inc: 18 P words followed by 4x256 S words.
"""
import sys

WORDS = 18 + 4 * 256
BITS = WORDS * 32 + 64  # guard bits


def arctan_inv(x: int, one: int) -> int:
    total, term, n, sign = 0, one // x, 1, 1
    x2 = x * x
    while term:
        total += sign * (term // n)
        term //= x2
        n += 2
        sign = -sign
    return total


def main() -> None:
    one = 1 << BITS
    pi = 4 * (4 * arctan_inv(5, one) - arctan_inv(239, one))
    frac = pi - 3 * one
    words = []
    for i in range(WORDS):
        shift = BITS - 32 * (i + 1)
        words.append((frac >> shift) & 0xFFFFFFFF)
    out = sys.argv[1] if len(sys.argv) > 1 else "src/xi/blowfish_table.inc"
    with open(out, "w") as f:
        f.write("// Generated by tools/gen_blowfish_table.py: Blowfish P[18] then S[4][256] (hex digits of pi).\n")
        for i in range(0, WORDS, 8):
            f.write("    " + ", ".join(f"0x{w:08X}" for w in words[i:i + 8]) + ",\n")


if __name__ == "__main__":
    main()
