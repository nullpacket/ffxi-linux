"""Prepare Ashita's plugin SDK and open-source Ashita plugins for a native Linux build (issue #34,
docs/ashita-compat.md "Plugins").

Nothing this writes is committed: the SDK and the plugins are third-party code, read from the user's Ashita install /
clones and written into the build directory.

  ashita_sdk_port.py sdk SDK_DIR OUT_DIR
      Copies plugins/sdk to OUT_DIR, made to compile with GCC / Clang on x86-64 Linux: the DOS end-of-file bytes
      (0x1A) some DirectX 8 headers end with are dropped, and the static_asserts on the sizes of the game's 32-bit
      structures are disabled (pointers are 8 bytes here, so the raw structures are larger; plugin and client are built
      from the same headers, so they still agree). Writes OUT_DIR/xi_sdk_stubs.h: for every SDK interface a class
      XiStub_<Interface> that implements each pure virtual method with a do-nothing body returning a zero value, so the
      client implements only the methods it can answer.

  ashita_sdk_port.py plugin SRC_DIR OUT_DIR
      Copies a plugin's sources (and a sibling `common` folder, which Thorny's plugins include as ..\\common) to
      OUT_DIR/<name>, with Windows path separators in #include lines and in path string literals ("\\\\") turned into
      '/', and #include names matched to the files' real case.
"""

from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

SOURCE_EXT = {".h", ".hpp", ".inl", ".cpp", ".c", ".cc"}

# A pure virtual method: everything between `virtual` and `= 0;` (return type, name, parameters, const).
PURE = re.compile(r"virtual\s+([^;{}]*?\))\s*(const)?\s*=\s*0\s*;", re.S)
# An interface (struct / class / the COM `interface` macro) named I<Upper>..., with its optional bases.
IFACE = re.compile(r"^\s*(?:struct|class|interface)\s+(I[A-Z]\w*)\s*(?::\s*([^{\n]+))?\s*\n?\s*\{", re.M)
SIZE_ASSERT = re.compile(r"^(\s*)(static_assert\s*\(\s*sizeof\b.*)$", re.M)


def _body(text: str, open_brace: int) -> str:
    """The text of the brace block that starts at `open_brace`."""
    depth = 0
    for i in range(open_brace, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[open_brace + 1 : i]
    return text[open_brace + 1 :]


def _strip_comments(text: str) -> str:
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


def interfaces(headers: list[Path]) -> dict[str, tuple[list[str], list[tuple[str, bool]]]]:
    """name -> (bases, [(signature, const)]) for every interface with pure virtual methods."""
    found: dict[str, tuple[list[str], list[tuple[str, bool]]]] = {}
    for h in headers:
        text = _strip_comments(h.read_text(encoding="latin-1"))
        for m in IFACE.finditer(text):
            name = m.group(1)
            bases = [b.split()[-1] for b in (m.group(2) or "").split(",") if b.strip()]
            body = _body(text, m.end() - 1)
            methods = [(" ".join(p.group(1).split()), bool(p.group(2))) for p in PURE.finditer(body)]
            if methods or name in found:
                found.setdefault(name, (bases, []))[1].extend(methods)
            elif bases:
                found[name] = (bases, [])
    return found


def stubs(found: dict[str, tuple[list[str], list[tuple[str, bool]]]]) -> str:
    out = [
        "// Generated by tools/ashita_sdk_port.py from the Ashita SDK: do-nothing implementations of every interface.",
        "#pragma once",
        "#pragma GCC system_header",
        '#include "Ashita.h"',
        "",
    ]

    def all_methods(name: str, seen: set[str]) -> list[tuple[str, bool]]:
        if name not in found or name in seen:
            return []
        seen.add(name)
        bases, methods = found[name]
        result: list[tuple[str, bool]] = []
        for b in bases:
            result += all_methods(b, seen)
        return result + methods

    for name in sorted(found):
        methods = all_methods(name, set())
        if not methods:
            continue
        out.append(f"struct XiStub_{name} : public {name}")
        out.append("{")
        for sig, const in methods:
            head = sig[: sig.index("(")].strip()
            ret = head.rsplit(None, 1)[0] if " " in head else ""
            for macro in ("STDMETHODCALLTYPE", "IMGUI_API"):
                ret = ret.replace(macro, "")
            ret = " ".join(ret.split())
            if ret in ("void", ""):
                body = "{}"
            elif ret.endswith("&"):
                body = f"{{ static {ret[:-1].strip().removeprefix('const ')} v{{}}; return v; }}"
            else:
                body = "{ return {}; }"
            out.append(f"    {sig}{' const' if const else ''} override {body}")
        out.append("};")
        out.append("")
    return "\n".join(out)


def port_sdk(src: Path, dst: Path) -> None:
    if dst.exists():
        shutil.rmtree(dst)
    shutil.copytree(src, dst, ignore=shutil.ignore_patterns("lib", "*.lib"))
    headers = []
    for f in sorted(dst.rglob("*")):
        if f.suffix.lower() not in SOURCE_EXT:
            continue
        raw = f.read_bytes().replace(b"\x1a", b"")
        text = raw.decode("latin-1")
        text = SIZE_ASSERT.sub(r"\1// (ffxi-linux: 64-bit layout) \2", text)
        # REG_DWORD is an unsigned long in the Windows SDK and an int in Wine's headers.
        text = re.sub(r"\bauto(\s+\w+\s*=\s*REG_DWORD\s*;)", r"DWORD\1", text)
        f.write_text(text, encoding="latin-1")
        headers.append(f)
    (dst / "xi_sdk_stubs.h").write_text(stubs(interfaces(headers)), encoding="latin-1")


INCLUDE = re.compile(r'^(\s*#\s*include\s*)([<"])([^>"]+)([>"])', re.M)


def _fix_case(base: Path, rel: str) -> str:
    """`rel` (relative to `base`) with each part matched to an existing file or folder ignoring case."""
    cur = base
    parts = []
    for part in rel.split("/"):
        if part in ("", ".", ".."):
            parts.append(part)
            cur = cur / part
            continue
        hit = part
        if cur.is_dir():
            for c in cur.iterdir():
                if c.name.lower() == part.lower():
                    hit = c.name
                    break
        parts.append(hit)
        cur = cur / hit
    return "/".join(parts)


def _port_file(f: Path) -> None:
    text = f.read_bytes().replace(b"\x1a", b"").decode("latin-1")

    def inc(m: re.Match[str]) -> str:
        path = m.group(3).replace("\\", "/")
        # An absolute Windows path to the SDK ("C:/Ashita 4/plugins/sdk/Ashita.h") is found through the include path.
        if re.match(r"[A-Za-z]:/", path):
            path = re.sub(r"(?i)^.*?/plugins/sdk/", "", path) if "/sdk/" in path.lower() else path.rsplit("/", 1)[-1]
        if m.group(2) == '"':
            path = _fix_case(f.parent, path)
        return f"{m.group(1)}{m.group(2)}{path}{m.group(4)}"

    text = INCLUDE.sub(inc, text)
    # Path separators in string literals: "\\config\\stylist\\" -> "/config/stylist/".
    text = text.replace("\\\\", "/")
    f.write_text(text, encoding="latin-1")


def port_plugin(src: Path, dst_root: Path) -> Path:
    dst = dst_root / src.name
    if dst.exists():
        shutil.rmtree(dst)
    keep = shutil.ignore_patterns(".git", "build", "*.sln", "*.vcxproj*", "*.dll", "*.lib", "*.pdb")
    shutil.copytree(src, dst, ignore=keep)
    common = src.parent / "common"
    if common.is_dir() and src.name != "common":
        if (dst_root / "common").exists():
            shutil.rmtree(dst_root / "common")
        shutil.copytree(common, dst_root / "common", ignore=keep)
    for d in (dst, dst_root / "common"):
        if not d.is_dir():
            continue
        for f in sorted(d.rglob("*")):
            if f.is_file() and f.suffix.lower() in SOURCE_EXT:
                _port_file(f)
    return dst


def main(argv: list[str]) -> int:
    if len(argv) != 4 or argv[1] not in ("sdk", "plugin"):
        print(__doc__, file=sys.stderr)
        return 2
    src, dst = Path(argv[2]), Path(argv[3])
    if not src.is_dir():
        print(f"ashita_sdk_port: no such folder: {src}", file=sys.stderr)
        return 1
    if argv[1] == "sdk":
        port_sdk(src, dst)
    else:
        port_plugin(src, dst)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
